"""Monte Carlo baseline for the program schedule.

Reads the three-point estimates (O, M, P in hours) for every work package from
pm-baselines/wbs.md, samples each package, sums the samples, and reports the
distribution of total effort. Run from the repository root:

    python3 scripts/monte_carlo_baseline.py

Writes pm-baselines/monte-carlo-baseline.md and pm-baselines/monte-carlo-baseline.png.
Fixed seed, so the same inputs always give the same output.
"""
import re
import sys
from pathlib import Path

import numpy as np

SEED = 20261105
N = 10_000
HOURS_PER_WEEK = 35.0  # the figure stated in the WBS summary

root = Path(__file__).resolve().parent.parent
wbs = (root / "pm-baselines" / "wbs.md").read_text()

rows = []   # (id, name, O, M, P)
for line in wbs.splitlines():
    m = re.match(r"\|\s*(\d+\.\d+\.\d+)\s*\|\s*(.+?)\s*\|\s*([\d.]+)\s*\|\s*([\d.]+)\s*\|\s*([\d.]+)\s*\|\s*([\d.]+)\s*\|", line)
    if m:
        rows.append((m.group(1), m.group(2), float(m.group(3)), float(m.group(4)), float(m.group(5))))
if not rows:
    sys.exit("No work packages found in wbs.md")

O = np.array([r[2] for r in rows]); M = np.array([r[3] for r in rows]); P = np.array([r[4] for r in rows])
if not (np.all(O <= M) and np.all(M <= P)):
    sys.exit("Estimate order problem: O <= M <= P must hold for every package")

rng = np.random.default_rng(SEED)

def pert(rng, o, m, p, n, lam=4.0):
    span = p - o
    out = np.empty((n, len(o)))
    for j in range(len(o)):
        if span[j] == 0:
            out[:, j] = o[j]
        else:
            a = 1 + lam * (m[j] - o[j]) / span[j]
            b = 1 + lam * (p[j] - m[j]) / span[j]
            out[:, j] = o[j] + span[j] * rng.beta(a, b, n)
    return out

def tri(rng, o, m, p, n):
    out = np.empty((n, len(o)))
    for j in range(len(o)):
        out[:, j] = o[j] if p[j] == o[j] else rng.triangular(o[j], m[j], p[j], n)
    return out

pert_s = pert(rng, O, M, P, N)
tri_s = tri(rng, O, M, P, N)
tot_pert = pert_s.sum(axis=1)
tot_tri = tri_s.sum(axis=1)
expected = ((O + 4 * M + P) / 6).sum()

def stats(x):
    return {k: float(np.percentile(x, q)) for k, q in (("P10", 10), ("P50", 50), ("P80", 80), ("P90", 90))} | {"mean": float(x.mean()), "sd": float(x.std())}

sp, st = stats(tot_pert), stats(tot_tri)

# per-section subtotals (PERT-beta)
sections = {}
for i, r in enumerate(rows):
    sections.setdefault(r[0].split(".")[0], []).append(i)
sec_lines = []
for s in sorted(sections, key=int):
    x = pert_s[:, sections[s]].sum(axis=1)
    sec_lines.append(f"| {s}.0 | {len(sections[s])} | {((O+4*M+P)/6)[sections[s]].sum():.1f} | {np.percentile(x,50):.1f} | {np.percentile(x,80):.1f} |")

# chart
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
fig, ax = plt.subplots(figsize=(8, 4.5), dpi=150)
ax.hist(tot_pert, bins=60, color="#7a9cc6", edgecolor="white", linewidth=0.4)
for val, lab, col, ls in ((sp["P50"], f"P50 {sp['P50']:.0f} h", "#1f3a5f", "-"), (sp["P80"], f"P80 {sp['P80']:.0f} h", "#b5472f", "-"), (expected, f"Sum of expected values {expected:.1f} h", "#555555", "--")):
    ax.axvline(val, color=col, linestyle=ls, linewidth=1.6, label=lab)
ax.set_xlabel("Total program effort (hours)")
ax.set_ylabel("Simulation runs")
ax.set_title("Program effort baseline, 10,000 runs (PERT-beta, independent tasks)")
ax.legend(frameon=False)
for side in ("top", "right"):
    ax.spines[side].set_visible(False)
fig.tight_layout()
fig.savefig(root / "pm-baselines" / "monte-carlo-baseline.png")

md = f"""# Monte Carlo Baseline: Program Effort

**Generated by:** `scripts/monte_carlo_baseline.py`
**Inputs:** `pm-baselines/wbs.md`, {len(rows)} work packages, three-point estimates in hours
**Status:** Baseline. Produced before pathfinder replication begins. Not edited afterwards.

## Assumptions

- **Distribution:** PERT-beta (shape parameter 4) for each work package. A triangular distribution is run as a sensitivity check.
- **Iterations:** {N:,}. Fixed random seed ({SEED}), so the run can be reproduced exactly.
- **Independence:** work packages are treated as statistically independent. No correlation between packages is modelled.
- **Quantity simulated:** total effort in hours, the sum of all work packages. It is not a calendar duration.
- **Conversion to weeks:** divided by {HOURS_PER_WEEK:.0f} hours per week, the figure stated in the WBS summary.
- **Inputs are the original baseline estimates.** Nothing is adjusted for work already done.

## Results

| Measure | PERT-beta (primary) | Triangular (check) |
|---|---|---|
| Sum of expected values (deterministic) | {expected:.1f} h | {expected:.1f} h |
| Mean | {sp['mean']:.1f} h | {st['mean']:.1f} h |
| P10 | {sp['P10']:.1f} h | {st['P10']:.1f} h |
| **P50** | **{sp['P50']:.1f} h** ({sp['P50']/HOURS_PER_WEEK:.1f} weeks) | {st['P50']:.1f} h ({st['P50']/HOURS_PER_WEEK:.1f} weeks) |
| **P80** | **{sp['P80']:.1f} h** ({sp['P80']/HOURS_PER_WEEK:.1f} weeks) | {st['P80']:.1f} h ({st['P80']/HOURS_PER_WEEK:.1f} weeks) |
| P90 | {sp['P90']:.1f} h | {st['P90']:.1f} h |
| Standard deviation | {sp['sd']:.1f} h | {st['sd']:.1f} h |

![Distribution of total program effort](monte-carlo-baseline.png)

### By WBS section (PERT-beta)

| Section | Packages | Sum of expected (h) | P50 (h) | P80 (h) |
|---|---|---|---|---|
""" + "\n".join(sec_lines) + f"""

## Limitations

- **Independence understates the spread.** Real delays tend to be correlated: a bad week affects many packages at once. Treating packages as independent makes the total distribution narrower than it probably is, so the P80 here is likely optimistic.
- **Effort is not duration.** Package 4.2.2 (initial synchronization) is elapsed waiting time and sits on the critical path. Summing effort does not capture waiting or the order of work. A schedule simulation along the dependency path would be needed for that.
- **The estimates are the author's own judgment.** The simulation spreads them out, but it cannot correct a bias in them. If every estimate is low, so is every percentile.
- **Pessimistic values are not hard limits.** The distributions are bounded by O and P. A real overrun beyond P cannot appear here.
- **One operator, one project.** The result describes this plan, not migration programs in general.

## How this is used

After the pathfinder, the same script is run again with measured values in place of the planning estimates for the pathfinder packages. The change in P50 and P80 is reported in Chapter 5.
"""
(root / "pm-baselines" / "monte-carlo-baseline.md").write_text(md)
print(f"packages={len(rows)} expected={expected:.1f}")
print("PERT", {k: round(v, 1) for k, v in sp.items()})
print("TRI ", {k: round(v, 1) for k, v in st.items()})
